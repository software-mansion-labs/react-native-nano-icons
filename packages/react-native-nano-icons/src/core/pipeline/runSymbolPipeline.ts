import fsp from 'node:fs/promises';
import path from 'node:path';

import { PathKitManager } from './managers.js';
import { ensureDir, ensureEmptyDir } from './config.js';
import { prepareSvgLayers } from './prepare.js';
import { shouldSkipPath } from '../svg/svg_dom.js';
import { resolveSymbolLayers, contentBounds } from '../svg/svg_pathops.js';
import { buildSymbolTemplate } from '../symbols/template.js';
import { buildColoredSymbolSvg } from '../symbols/coloredSymbol.js';
import { buildVectorDrawableXml } from '../symbols/vectorDrawable.js';
import {
  symbolsetContentsJson,
  imagesetContentsJson,
} from '../symbols/contents.js';
import {
  toDrawableResourceName,
  manifestBaseName,
} from '../../utils/naming.js';
import type { NanoLogger } from '../types.js';

export type SymbolsPipelineConfig = {
  /** Set name (used for output filenames and the manifest export name). */
  name: string;
  /** Symbol name prefix, e.g. "nano" → "nano.home". */
  prefix: string;
  /** Emit colored `.imageset` (original colors) instead of monochrome `.symbolset`. */
  multicolor?: boolean;
};

export type SymbolsPipelinePaths = {
  inputDir: string;
  outputDir: string;
};

// Mirrors the glyphmap house style: m - metadata (p prefix, h input hash),
// s - symbols (icon → iOS symbol name), d - drawables (icon → Android resource name).
export type NanoSymbolMap = {
  m: { p: string; h?: string };
  s: Record<string, string>;
  d: Record<string, string>;
};

export type SymbolsPipelineResult = {
  name: string;
  prefix: string;
  /** Directory containing the generated `.symbolset`/`.imageset` folders. */
  symbolsDir: string;
  /** The generated asset folders (`.symbolset` for symbols, `.imageset` for colored symbols). */
  assetDirs: string[];
  /** Directory containing the generated Android VectorDrawable `.xml` files. */
  drawablesDir: string;
  /** The generated VectorDrawable `.xml` file paths. */
  drawableFiles: string[];
  manifestTsPath: string;
  symbolmapPath: string;
  symbols: Record<string, string>;
  /** Icon → Android drawable resource name (e.g. "home" → "nano_home"). */
  drawables: Record<string, string>;
};

function manifestTs(
  exportName: string,
  typeName: string,
  entries: Record<string, string>
): string {
  const lines = Object.entries(entries)
    .map(
      ([icon, value]) => `  ${JSON.stringify(icon)}: ${JSON.stringify(value)},`
    )
    .join('\n');
  return `// Generated by react-native-nano-icons — do not edit.
export const ${exportName} = {
${lines}
} as const;

export type ${typeName} =
  (typeof ${exportName})[keyof typeof ${exportName}];
`;
}

/**
 * Run the symbol pipeline: prep each SVG, then emit one asset per icon — a
 * monochrome `.symbolset`, or a colored `.imageset` when `multicolor` is set.
 * Also writes a typed manifest and a symbolmap JSON (for build fingerprinting).
 */
export async function runSymbolPipeline(
  config: SymbolsPipelineConfig,
  paths: SymbolsPipelinePaths,
  options?: { logger?: NanoLogger; inputHash?: string }
): Promise<SymbolsPipelineResult> {
  const startTime = Date.now();
  const logger = options?.logger;
  const kind = config.multicolor ? 'colored symbol' : 'symbol';

  logger?.update(`Building ${kind}s "${config.name}"…`);

  ensureDir(paths.outputDir);
  const symbolsDir = path.join(paths.outputDir, `${config.name}.symbols`);
  ensureEmptyDir(symbolsDir);
  const drawablesDir = path.join(paths.outputDir, `${config.name}.drawables`);
  ensureEmptyDir(drawablesDir);

  const files = (await fsp.readdir(paths.inputDir))
    .filter((f) => f.toLowerCase().endsWith('.svg'))
    .sort();

  const symbols: Record<string, string> = {};
  const drawables: Record<string, string> = {};
  const assetDirs: string[] = [];
  const drawableFiles: string[] = [];
  const usedResourceNames = new Set<string>();

  const PathKit = await PathKitManager.getInstance();

  for (const file of files) {
    const iconName = path.parse(file).name;
    const filePath = path.join(paths.inputDir, file);

    logger?.info(`Processing ${file}`);

    const prepared = await prepareSvgLayers({
      filePath,
      fileLabel: `${config.name}:${file}`,
      PathKit,
      logger,
    });
    if (!prepared) continue;

    const drawable = prepared.paths.filter((p) => !shouldSkipPath(p.d, p.fill));

    if (drawable.length === 0) {
      logger?.warn(`Skipping "${config.name}:${file}": no drawable paths`);
      continue;
    }

    const assetName = `${config.prefix}.${iconName}`;
    let assetDir: string;
    let svgFilename: string;
    let svg: string;
    let contents: string;
    let vdXml: string;

    if (config.multicolor) {
      // Colored symbol: original fills/z-order, no knockout.
      const coloredLayers = drawable.map((p) => ({ d: p.d, fill: p.fill }));
      const bounds =
        contentBounds(
          PathKit,
          drawable.map((p) => p.d)
        ) ?? undefined;
      assetDir = path.join(symbolsDir, `${assetName}.imageset`);
      svgFilename = `${assetName}.svg`;
      svg = buildColoredSymbolSvg({
        layers: coloredLayers,
        viewBox: prepared.viewBox,
        contentBounds: bounds,
      });
      contents = imagesetContentsJson(svgFilename);
      vdXml = buildVectorDrawableXml({
        layers: coloredLayers,
        multicolor: true,
        viewBox: prepared.viewBox,
        contentBounds: bounds,
      });
    } else {
      // Monochrome SF Symbol: resolve stacked layers (bake knockouts, occlude)
      // so plates with light details survive monochrome tinting.
      const layers = resolveSymbolLayers(PathKit, drawable, {
        onEraseLayer: () =>
          logger?.info(`    ⊖ Baked white knockout layer into lower layers`),
      });
      const bounds =
        contentBounds(
          PathKit,
          layers.map((l) => l.d)
        ) ?? undefined;
      assetDir = path.join(symbolsDir, `${assetName}.symbolset`);
      svgFilename = `${assetName}.svg`;
      svg = buildSymbolTemplate({
        layers,
        viewBox: prepared.viewBox,
        contentBounds: bounds,
        descriptiveName: assetName,
        logger,
      });
      contents = symbolsetContentsJson(svgFilename);
      vdXml = buildVectorDrawableXml({
        layers,
        multicolor: false,
        viewBox: prepared.viewBox,
        contentBounds: bounds,
      });
    }

    await fsp.mkdir(assetDir, { recursive: true });
    await fsp.writeFile(path.join(assetDir, svgFilename), svg, 'utf8');
    await fsp.writeFile(path.join(assetDir, 'Contents.json'), contents, 'utf8');

    // Android VectorDrawable — resource names must be unique within the set.
    let resourceName = toDrawableResourceName(assetName);
    if (usedResourceNames.has(resourceName)) {
      let n = 2;
      while (usedResourceNames.has(`${resourceName}_${n}`)) n++;
      logger?.warn(
        `Drawable name collision for "${assetName}" → "${resourceName}_${n}"`
      );
      resourceName = `${resourceName}_${n}`;
    }
    usedResourceNames.add(resourceName);
    const drawableFile = path.join(drawablesDir, `${resourceName}.xml`);
    await fsp.writeFile(drawableFile, vdXml, 'utf8');

    symbols[iconName] = assetName;
    drawables[iconName] = resourceName;
    assetDirs.push(assetDir);
    drawableFiles.push(drawableFile);
  }

  const symbolmapPath = path.join(
    paths.outputDir,
    `${config.name}.symbolmap.json`
  );
  const symbolmap: NanoSymbolMap = {
    m: {
      p: config.prefix,
      ...(options?.inputHash ? { h: options.inputHash } : {}),
    },
    s: symbols,
    d: drawables,
  };
  await fsp.writeFile(symbolmapPath, JSON.stringify(symbolmap), 'utf8');

  const base = manifestBaseName(config.name);
  const manifestTsPath = path.join(
    paths.outputDir,
    `${config.name}.symbols.ts`
  );
  await fsp.writeFile(
    manifestTsPath,
    manifestTs(`${base}Symbols`, `${base}SymbolName`, symbols),
    'utf8'
  );

  const drawablesTsPath = path.join(
    paths.outputDir,
    `${config.name}.drawables.ts`
  );
  await fsp.writeFile(
    drawablesTsPath,
    manifestTs(`${base}Drawables`, `${base}DrawableName`, drawables),
    'utf8'
  );

  const count = assetDirs.length;
  const elapsed = Date.now() - startTime;
  logger?.succeed(
    `Built ${config.name} ${kind}s [${count} ${kind}${count === 1 ? '' : 's'} in ${elapsed}ms]`
  );

  return {
    name: config.name,
    prefix: config.prefix,
    symbolsDir,
    assetDirs,
    drawablesDir,
    drawableFiles,
    manifestTsPath,
    symbolmapPath,
    symbols,
    drawables,
  };
}
